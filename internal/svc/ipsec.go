// ipsecSvc runs the strongSwan IKE daemon (charon) and loads connections from crypto-maps and profiles into it.
// Traffic encryption is done by the kernel (xfrm): charon installs the policies from the local-ts/remote-ts selectors.
// filter-map rules with set crypto-map let traffic through in nftables (see fmap.go).
//
// Files in the run directory (/run/necorouter): strongswan.conf (charon parameters), swanctl.conf (connections, 0600).
// The router does not install strongSwan: if charon or swanctl are not found, there is no service and warnings carry a hint.
type ipsecSvc struct{ loaded string }

func (*ipsecSvc) Name() string { return "ipsec" }

var ipsecIdent = regexp.MustCompile(`[^A-Za-z0-9_.-]`)

// sq quotes a value for swanctl.conf: in double quotes, with \ and " escaped.
func sq(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

type ipsecConn struct {
	name string
	m    *config.CryptoMap
	p    *config.IPsecProfile
}

// ipsecConns selects crypto-map entries that have everything required; the others produce a warning.
func ipsecConns(c *config.Config) ([]ipsecConn, []string) {
	var out []ipsecConn
	var warns []string
	uses := map[string]int{}
	for _, m := range c.CryptoMaps {
		uses[m.Profile]++
	}
	for _, m := range c.CryptoMaps {
		w := func(f string, a ...any) {
			warns = append(warns, fmt.Sprintf("crypto-map %s %d: ", m.Name, m.Seq)+fmt.Sprintf(f, a...))
		}
		if m.Peer == "" {
			w("no 'match peer', the entry is skipped")
			continue
		}
		if m.Profile == "" {
			w("no 'set crypto-ipsec profile', the entry is skipped")
			continue
		}
		p := c.FindIPsecProfile(m.Profile)
		if p == nil {
			w("profile %s does not exist, the entry is skipped", m.Profile)
			continue
		}
		switch {
		case p.P1Proposal == "":
			w("profile %s has no ike-phase1 proposal, the entry is skipped", p.Name)
			continue
		case p.PSK == "" && p.LocalPSK == nil && p.RemotePSK == nil:
			w("profile %s has no pre-shared key (ike-phase1), the entry is skipped", p.Name)
			continue
		case p.P2Proposal == "":
			w("profile %s has no ike-phase2 proposal, the entry is skipped", p.Name)
			continue
		case p.LocalTS == "" || p.RemoteTS == "":
			w("profile %s needs local-ts and remote-ts (ike-phase2), the entry is skipped", p.Name)
			continue
		}
		name := ipsecIdent.ReplaceAllString(p.Name, "_")
		if uses[p.Name] > 1 {
			name += "_" + ipsecIdent.ReplaceAllString(m.Peer, "_")
		}
		out = append(out, ipsecConn{name: name, m: m, p: p})
	}
	return out, warns
}

// ipsecSwanctl builds swanctl.conf.
func ipsecSwanctl(c *config.Config) (string, []string, int) {
	conns, warns := ipsecConns(c)
	var b strings.Builder
	var secrets strings.Builder
	b.WriteString("# generated by necorouter\nconnections {\n")
	for n, cn := range conns {
		p, m := cn.p, cn.m
		ver := 2
		if p.Version == "ike-v1" {
			ver = 1
		}
		mode := p.Mode
		if mode == "" {
			mode = "tunnel"
		}
		if ver == 2 && mode == "transport" {
			warns = append(warns, fmt.Sprintf("profile %s: IKEv2 works in tunnel mode only, tunnel is used", p.Name))
			mode = "tunnel"
		}
		fmt.Fprintf(&b, "  %s {\n    version = %d\n    remote_addrs = %s\n", cn.name, ver, m.Peer)
		if p.NATT && ver == 1 {
			b.WriteString("    encap = yes\n")
		}
		fmt.Fprintf(&b, "    proposals = %s\n", sq(strings.ToLower(p.P1Proposal)))
		b.WriteString("    local {\n      auth = psk\n")
		if p.LocalPSK != nil {
			fmt.Fprintf(&b, "      id = %s\n", sq(p.LocalPSK.ID))
		}
		b.WriteString("    }\n    remote {\n      auth = psk\n")
		if p.RemotePSK != nil {
			fmt.Fprintf(&b, "      id = %s\n", sq(p.RemotePSK.ID))
		}
		b.WriteString("    }\n    children {\n")
		fmt.Fprintf(&b, "      %s {\n        mode = %s\n", cn.name, mode)
		fmt.Fprintf(&b, "        local_ts = %s\n        remote_ts = %s\n", strings.Join(config.TSList(p.LocalTS), ","), strings.Join(config.TSList(p.RemoteTS), ","))
		fmt.Fprintf(&b, "        esp_proposals = %s\n", sq(strings.ToLower(p.P2Proposal)))
		if p.Rekey > 0 {
			fmt.Fprintf(&b, "        rekey_time = %ds\n", p.Rekey)
		}
		b.WriteString("        start_action = trap\n      }\n    }\n  }\n")

		if p.PSK != "" {
			fmt.Fprintf(&secrets, "  ike-%d {\n    id-1 = %s\n    secret = %s\n  }\n", n, sq(m.Peer), sq(p.PSK))
		}
		if p.LocalPSK != nil {
			fmt.Fprintf(&secrets, "  ike-%dl {\n    id-1 = %s\n    secret = %s\n  }\n", n, sq(p.LocalPSK.ID), sq(p.LocalPSK.Data))
		}
		if p.RemotePSK != nil {
			fmt.Fprintf(&secrets, "  ike-%dr {\n    id-1 = %s\n    secret = %s\n  }\n", n, sq(p.RemotePSK.ID), sq(p.RemotePSK.Data))
		}
	}
	b.WriteString("}\n")
	if secrets.Len() > 0 {
		b.WriteString("secrets {\n" + secrets.String() + "}\n")
	}
	return b.String(), warns, len(conns)
}

func (*ipsecSvc) paths(env *Env) (strongswan, swanctl, sock, pid string) {
	return env.P.Run + "/strongswan.conf", env.P.Run + "/swanctl.conf", env.P.Run + "/charon.vici", env.P.Run + "/charon.pid"
}

// ipsecStrongswan holds the charon parameters: vici socket and pid file in the run directory; the router installs routes itself.
func ipsecStrongswan(sock, pid string) string {
	var b strings.Builder
	if st, err := os.Stat("/etc/strongswan.conf"); err == nil && !st.IsDir() {
		b.WriteString("include /etc/strongswan.conf\n")
	}
	fmt.Fprintf(&b, "charon {\n  pid_file = %s\n  install_routes = no\n  install_virtual_ip = no\n", pid)
	b.WriteString("  filelog {\n    stderr {\n      default = 1\n      flush_line = yes\n    }\n  }\n")
	fmt.Fprintf(&b, "  plugins {\n    vici {\n      socket = unix://%s\n    }\n  }\n}\n", sock)
	return b.String()
}

func (s *ipsecSvc) Apply(env *Env, c *config.Config) ([]string, error) {
	swan, warns, n := ipsecSwanctl(c)
	if !c.IPsecIKE {
		if len(c.CryptoMaps) > 0 || len(c.IPsecProfiles) > 0 {
			warns = append(warns, "IPsec is inactive: 'crypto-ipsec ike enable' is not set")
		}
		s.Stop(env)
		return nil, nil
	}
	if n == 0 {
		s.Stop(env)
		return warns, nil
	}
	charon := find("charon", "/usr/lib/ipsec", "/usr/libexec/ipsec", "/usr/lib/strongswan", "/usr/libexec/strongswan")
	swanctl := find("swanctl")
	if charon == "" || swanctl == "" {
		s.Stop(env)
		return warns, fmt.Errorf("strongSwan is not installed (needed for crypto-ipsec; see packaging/DEPENDENCIES)")
	}
	envBin := find("env", "/usr/bin", "/bin")
	if envBin == "" {
		return warns, fmt.Errorf("env is not installed")
	}
	fStrong, fSwan, sock, pid := s.paths(env)
	strong := ipsecStrongswan(sock, pid)
	if err := writeFileAtomic(fStrong, []byte(strong), 0o644); err != nil {
		return warns, err
	}
	if err := writeFileAtomic(fSwan, []byte(swan), 0o600); err != nil {
		return warns, err
	}
	was := env.Sup.Running("charon")
	// Wrapper: after charon starts (including after a supervisor restart) it loads the connections.
	// TERM from the supervisor is forwarded to charon and the wrapper waits for it to exit (otherwise the new start would overlap the old one).
	script := `"$1" &
pid=$!
trap 'kill $pid 2>/dev/null' TERM INT
i=0
while [ ! -S "$2" ] && [ $i -lt 15 ]; do sleep 1; i=$((i+1)); done
"$3" --load-all --file "$4" --uri "unix://$2" >/dev/null 2>&1
wait $pid
wait $pid`
	argv := []string{envBin, "STRONGSWAN_CONF=" + fStrong, "sh", "-c", script, "sh", charon, sock, swanctl, fSwan}
	sig := fmt.Sprintf("%x", sha256.Sum256([]byte(strong)))
	if err := env.Sup.Ensure("charon", sig, argv); err != nil {
		return warns, err
	}
	sum := fmt.Sprintf("%x", sha256.Sum256([]byte(swan)))
	if !was || sum != s.loaded {
		for i := 0; i < 100; i++ { // wait up to 10 seconds for the vici socket
			if st, err := os.Stat(sock); err == nil && st.Mode()&os.ModeSocket != 0 {
				break
			}
			time.Sleep(100 * time.Millisecond)
		}
		if out, err := run(swanctl, "--load-all", "--file", fSwan, "--uri", "unix://"+sock); err != nil {
			return warns, fmt.Errorf("ipsec: %v", err)
		} else if strings.Contains(out, "failed") || strings.Contains(out, "error") {
			warns = append(warns, "ipsec: "+strings.ReplaceAll(out, "\n", "; "))
		}
		s.loaded = sum
	}
	return warns, nil
}

func (s *ipsecSvc) Stop(env *Env) error {
	env.Sup.Stop("charon")
	s.loaded = ""
	return nil
}

func (s *ipsecSvc) Status(env *Env) string {
	if env.Sup.Running("charon") {
		return "running (charon)"
	}
	if why := env.Sup.Why("charon"); why != "" {
		return "failed: " + why
	}
	return "idle"
}

// IPsecShow prints the IKE state: what is "connections" or "sas".
func IPsecShow(env *Env, what string) (string, error) {
	if env == nil || !env.Sup.Running("charon") {
		return "", fmt.Errorf("IKE is not running (crypto-ipsec ike enable, profile, crypto-map)")
	}
	_, _, sock, _ := (&ipsecSvc{}).paths(env)
	if what == "sas" {
		m, err := viciList(sock, "list-sas", "list-sa")
		if err != nil {
			return "", err
		}
		return formatSAs(m), nil
	}
	m, err := viciList(sock, "list-conns", "list-conn")
	if err != nil {
		return "", err
	}
	return formatConns(m), nil
}

// ipsecNames returns the connection names (for tests and diagnostics).
func ipsecNames(c *config.Config) []string {
	conns, _ := ipsecConns(c)
	var out []string
	for _, cn := range conns {
		out = append(out, cn.name)
	}
	sort.Strings(out)
	return out
}
